-- -------------------------------------------------------------------------------------
-- Tabla: poliza
-- -------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS poliza (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                    VARCHAR(20)    NOT NULL,  -- INDIVIDUAL | COLECTIVA
    estado                  VARCHAR(20)    NOT NULL,  -- ACTIVA | RENOVADA | CANCELADA
    tomador_id              VARCHAR(50),
    asegurado_id            VARCHAR(50),
    beneficiario_id         VARCHAR(50),
    fecha_inicio_vigencia   DATE           NOT NULL,
    fecha_fin_vigencia      DATE           NOT NULL,
    canon_mensual           NUMERIC(15,2)  NOT NULL,
    numero_meses_vigencia   INTEGER        NOT NULL,
    prima                   NUMERIC(15,2)  NOT NULL,
    ipc_aplicado            NUMERIC(6,3),
    fecha_creacion          TIMESTAMP      NOT NULL,
    fecha_actualizacion     TIMESTAMP,
    CONSTRAINT chk_poliza_tipo   CHECK (tipo IN ('INDIVIDUAL', 'COLECTIVA')),
    CONSTRAINT chk_poliza_estado CHECK (estado IN ('ACTIVA', 'RENOVADA', 'CANCELADA'))
);

-- -------------------------------------------------------------------------------------
-- Tabla: riesgo
-- -------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS riesgo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id           BIGINT         NOT NULL,
    estado              VARCHAR(20)    NOT NULL,  -- ACTIVO | CANCELADO
    inmueble_direccion  VARCHAR(300)   NOT NULL,
    canon_asociado      NUMERIC(15,2)  NOT NULL,
    fecha_creacion      TIMESTAMP      NOT NULL,
    fecha_cancelacion   DATE,
    CONSTRAINT fk_riesgo_poliza FOREIGN KEY (poliza_id) REFERENCES poliza (id),
    CONSTRAINT chk_riesgo_estado CHECK (estado IN ('ACTIVO', 'CANCELADO'))
);

-- Índice para acelerar la consulta de riesgos por póliza.
CREATE INDEX IF NOT EXISTS idx_riesgo_poliza_id ON riesgo (poliza_id);
